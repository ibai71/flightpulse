-- Run once in a Snowflake worksheet as ACCOUNTADMIN.
-- Creates a dedicated warehouse and least-privilege project role.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS FLIGHTPULSE_ROLE;

CREATE WAREHOUSE IF NOT EXISTS FLIGHTPULSE_WH
    WAREHOUSE_SIZE = XSMALL
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS FLIGHTPULSE;
CREATE SCHEMA IF NOT EXISTS FLIGHTPULSE.LANDING;
CREATE SCHEMA IF NOT EXISTS FLIGHTPULSE.ANALYTICS;

GRANT USAGE ON WAREHOUSE FLIGHTPULSE_WH TO ROLE FLIGHTPULSE_ROLE;
GRANT USAGE ON DATABASE FLIGHTPULSE TO ROLE FLIGHTPULSE_ROLE;
GRANT USAGE ON SCHEMA FLIGHTPULSE.LANDING TO ROLE FLIGHTPULSE_ROLE;
GRANT USAGE ON SCHEMA FLIGHTPULSE.ANALYTICS TO ROLE FLIGHTPULSE_ROLE;
GRANT CREATE TABLE ON SCHEMA FLIGHTPULSE.LANDING TO ROLE FLIGHTPULSE_ROLE;
GRANT CREATE STAGE ON SCHEMA FLIGHTPULSE.LANDING TO ROLE FLIGHTPULSE_ROLE;
GRANT CREATE FILE FORMAT ON SCHEMA FLIGHTPULSE.LANDING TO ROLE FLIGHTPULSE_ROLE;
GRANT CREATE TABLE ON SCHEMA FLIGHTPULSE.ANALYTICS TO ROLE FLIGHTPULSE_ROLE;
GRANT CREATE VIEW ON SCHEMA FLIGHTPULSE.ANALYTICS TO ROLE FLIGHTPULSE_ROLE;

USE DATABASE FLIGHTPULSE;
USE SCHEMA LANDING;

CREATE FILE FORMAT IF NOT EXISTS PARQUET_FORMAT TYPE = PARQUET USE_LOGICAL_TYPE = TRUE;
CREATE STAGE IF NOT EXISTS FLIGHTPULSE_STAGE FILE_FORMAT = (FORMAT_NAME = 'PARQUET_FORMAT');

CREATE TABLE IF NOT EXISTS BTS_FLIGHTS (
    FLIGHT_ID VARCHAR,
    FLIGHT_DATE DATE,
    AIRLINE_ID NUMBER(38, 0),
    AIRLINE_CODE VARCHAR,
    FLIGHT_NUMBER VARCHAR,
    ORIGIN_AIRPORT_ID NUMBER(38, 0),
    ORIGIN_CODE VARCHAR,
    DESTINATION_AIRPORT_ID NUMBER(38, 0),
    DESTINATION_CODE VARCHAR,
    SCHEDULED_DEPARTURE_HHMM NUMBER(10, 0),
    DEPARTURE_DELAY_MINUTES FLOAT,
    ARRIVAL_DELAY_MINUTES FLOAT,
    ARRIVAL_DELAYED_15 NUMBER(10, 0),
    CANCELLED BOOLEAN,
    DIVERTED BOOLEAN,
    DISTANCE_MILES FLOAT,
    AIR_TIME_MINUTES FLOAT,
    CARRIER_DELAY_MINUTES FLOAT,
    WEATHER_DELAY_MINUTES FLOAT,
    NAS_DELAY_MINUTES FLOAT,
    SECURITY_DELAY_MINUTES FLOAT,
    LATE_AIRCRAFT_DELAY_MINUTES FLOAT
);

CREATE TABLE IF NOT EXISTS ADSB_OBSERVATIONS (
    FLIGHT_ID VARCHAR,
    ICAO24 VARCHAR,
    CALLSIGN VARCHAR,
    ICAO_TYPE VARCHAR,
    OPERATOR_NAME VARCHAR,
    START_AIRPORT_IDENT VARCHAR,
    END_AIRPORT_IDENT VARCHAR,
    EVENT_TS TIMESTAMP_NTZ,
    EVENT_EPOCH NUMBER(38, 0),
    LONGITUDE FLOAT,
    LATITUDE FLOAT,
    ALTITUDE_FT FLOAT,
    TRACK_DEG FLOAT,
    GROUND_SPEED_KNOTS FLOAT,
    VERTICAL_RATE_FPM FLOAT,
    INDICATED_AIRSPEED_KNOTS FLOAT,
    HEIGHT_AGL_FT FLOAT
);

CREATE TABLE IF NOT EXISTS LOAD_AUDIT (
    RUN_ID VARCHAR,
    TABLE_NAME VARCHAR,
    FILES_UPLOADED NUMBER(10, 0),
    ROWS_LOADED NUMBER(38, 0),
    LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

GRANT OWNERSHIP ON ALL TABLES IN SCHEMA FLIGHTPULSE.LANDING TO ROLE FLIGHTPULSE_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL STAGES IN SCHEMA FLIGHTPULSE.LANDING TO ROLE FLIGHTPULSE_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL FILE FORMATS IN SCHEMA FLIGHTPULSE.LANDING TO ROLE FLIGHTPULSE_ROLE COPY CURRENT GRANTS;
